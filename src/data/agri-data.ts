export function calculateDistanceKm(
  coord1: [number, number],
  coord2: [number, number]
): number {
  const [lon1, lat1] = coord1;
  const [lon2, lat2] = coord2;

  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 10) / 10;
}

export function findOfficesWithinRadius(
  originCoords: [number, number],
  radiusKm: number = 30,
  offices: LoanOffice[] = LOAN_OFFICES
): Array<LoanOffice & { distanceKm: number }> {
  return offices
    .map((office) => ({
      ...office,
      distanceKm: calculateDistanceKm(originCoords, office.coords),
    }))
    .filter((office) => office.distanceKm <= radiusKm)
    .sort((a, b) => a.distanceKm - b.distanceKm);
}

export function estimateKccEligibility(
  landSizeAcres: number,
  primaryCrop: string
): {
  scaleOfFinancePerAcre: number;
  cropLoanLimit: number;
  postHarvestHouseholdLimit: number;
  maintenanceFarmAssetsLimit: number;
  totalSanctionLimit: number;
  subsidizedRate: number;
  annualInterestSaved: number;
} {
  let scalePerAcre = 35000;
  const cropLower = primaryCrop.toLowerCase();

  if (cropLower.includes("grape") || cropLower.includes("horticulture") || cropLower.includes("banana") || cropLower.includes("mango")) {
    scalePerAcre = 115000;
  } else if (cropLower.includes("sugarcane") || cropLower.includes("arecanut") || cropLower.includes("coconut")) {
    scalePerAcre = 75000;
  } else if (cropLower.includes("chilli") || cropLower.includes("cotton") || cropLower.includes("tobacco") || cropLower.includes("jeera") || cropLower.includes("jasmine")) {
    scalePerAcre = 58000;
  } else if (cropLower.includes("paddy") || cropLower.includes("rice")) {
    scalePerAcre = 42000;
  } else if (cropLower.includes("wheat") || cropLower.includes("mustard") || cropLower.includes("soybean") || cropLower.includes("potato") || cropLower.includes("groundnut")) {
    scalePerAcre = 40000;
  }

  const cropLoan = scalePerAcre * landSizeAcres;
  const postHarvest = cropLoan * 0.2;
  const maintenance = cropLoan * 0.1;
  const totalLimit = Math.min(Math.round(cropLoan + postHarvest + maintenance), 3000000);

  const subsidizedPortion = Math.min(totalLimit, 300000);
  const standardInterest = (subsidizedPortion * 7.0) / 100;
  const subsidizedInterest = (subsidizedPortion * 4.0) / 100;
  const annualSaved = standardInterest - subsidizedInterest;

  return {
    scaleOfFinancePerAcre: scalePerAcre,
    cropLoanLimit: Math.round(cropLoan),
    postHarvestHouseholdLimit: Math.round(postHarvest),
    maintenanceFarmAssetsLimit: Math.round(maintenance),
    totalSanctionLimit: totalLimit,
    subsidizedRate: 4.0,
    annualInterestSaved: Math.round(annualSaved),
  };
}

export function exportToCsv(data: Record<string, unknown>[], filename: string) {
  if (data.length === 0) return;
  const headers = Object.keys(data[0]);
  const rows = data.map((item) =>
    headers
      .map((header) => {
        const val = item[header];
        if (Array.isArray(val)) {
          return `"${val.join(", ")}"`;
        }
        if (typeof val === "string") {
          return `"${val.replace(/"/g, '""')}"`;
        }
        return val ?? "";
      })
      .join(",")
  );

  const csvContent = "data:text/csv;charset=utf-8," + [headers.join(","), ...rows].join("\n");
  const encodedUri = encodeURI(csvContent);
  const link = document.createElement("a");
  link.setAttribute("href", encodedUri);
  link.setAttribute("download", `${filename}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}

export function exportToGeoJson(features: GeoJSON.Feature[], filename: string) {
  const geojsonObj: GeoJSON.FeatureCollection = {
    type: "FeatureCollection",
    features,
  };
  const jsonStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(geojsonObj, null, 2));
  const link = document.createElement("a");
  link.setAttribute("href", jsonStr);
  link.setAttribute("download", `${filename}.geojson`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}
